async (page) => {
  const errors = [];
  const track = (tab) => {
    tab.on('pageerror', (error) => errors.push(error.message));
    tab.on('request', (request) => { if (request.url().includes('/api/auth/sync')) errors.push('Legacy sync was called'); });
  };
  track(page);
  const suffix = Date.now();
  const eventName = `Campus build ${suffix}`;
  const teamName = `Cobalt crew ${suffix}`;
  await page.goto('http://localhost:8080/auth/login?role=admin');
  await page.getByLabel('Email', { exact: true }).fill('organizer@example.test');
  await page.getByLabel('Password', { exact: true }).fill('browser-test-password');
  await page.getByRole('button', { name: 'Login', exact: true }).click();
  await page.waitForURL('**/admin');
  await page.getByRole('link', { name: 'Create event' }).click();
  await page.getByLabel('Event name', { exact: true }).fill(eventName);
  await page.getByLabel('Description', { exact: true }).fill('Build a useful project with your campus team.');
  await page.getByLabel('Theme', { exact: true }).fill('Ideas into action');
  await page.getByLabel('Start date', { exact: true }).fill('2099-11-08');
  await page.getByLabel('End date', { exact: true }).fill('2099-11-09');
  await page.getByLabel('Registration deadline', { exact: true }).fill('2099-11-07');
  await page.getByLabel('Minimum team size').fill('2');
  await page.getByLabel('Registration status').selectOption('Open');
  await page.getByRole('button', { name: 'Create event', exact: true }).click();
  await page.waitForURL('**/events/*');
  const eventUrl = page.url();
  await page.getByRole('heading', { name: eventName, exact: true }).waitFor();

  const studentContext = await page.context().browser().newContext();
  const student = await studentContext.newPage();
  track(student);
  try {
    await student.goto('http://localhost:8080/auth/signup?role=student');
    await student.getByLabel('Name', { exact: true }).fill('Campus Student');
    await student.getByLabel('Email', { exact: true }).fill(`student-${suffix}@example.test`);
    await student.getByLabel('Password', { exact: true }).fill('browser-test-password');
    await student.getByRole('button', { name: 'Sign Up', exact: true }).click();
    await student.waitForURL('**/student');
    await student.goto(eventUrl);
    await student.getByLabel('Team name').fill(teamName);
    await student.getByRole('button', { name: 'Add teammate', exact: true }).click();
    await student.getByLabel('Name', { exact: true }).fill('Campus Teammate');
    await student.getByLabel('Email', { exact: true }).fill(`teammate-${suffix}@example.test`);
    await student.getByRole('button', { name: 'Register team', exact: true }).click();
    await student.getByText('Your team is registered.', { exact: true }).waitFor();
    await student.getByLabel('Submission name').fill('Our repository');
    await student.getByLabel('GitHub URL').fill('https://github.com/campus/project');
    await student.getByRole('button', { name: 'Save submission', exact: true }).click();
    await student.getByText('Submission saved.', { exact: true }).waitFor();
    await student.getByLabel('Submission type').selectOption('presentation');
    await student.getByLabel('Submission name').fill('Our pitch');
    await student.getByLabel('Presentation link (HTTPS)').fill('');
    await student.getByLabel('Or upload a PDF (up to 10 MB)').setInputFiles({ name: 'pitch.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4\n1 0 obj<</Type/Catalog>>endobj\n%%EOF') });
    await student.getByRole('button', { name: 'Save submission', exact: true }).click();
    await student.getByText('Submission saved.', { exact: true }).waitFor();
    await student.getByRole('button', { name: 'Download PDF', exact: true }).waitFor();
    await student.reload();
    await student.getByRole('heading', { name: teamName, exact: true }).waitFor();
    await student.getByRole('button', { name: 'Download PDF', exact: true }).waitFor();
    const downloadReady = student.waitForEvent('download');
    await student.getByRole('button', { name: 'Download PDF', exact: true }).click();
    const downloaded = await downloadReady;
    if (await downloaded.failure()) throw new Error('PDF download failed');
    await student.getByRole('button', { name: 'Generate pass', exact: true }).click();
    const passCode = student.getByLabel('Pass code', { exact: true });
    await passCode.waitFor();
    const firstPass = await passCode.inputValue();
    await student.getByRole('button', { name: 'Generate pass', exact: true }).click();
    await student.waitForFunction((previous) => document.querySelector('input[readonly]')?.value !== previous, firstPass);
    const pass = await passCode.inputValue();
    await page.reload();
    await page.getByRole('heading', { name: teamName, exact: true }).waitFor();
    await page.getByRole('button', { name: 'Download PDF', exact: true }).waitFor();
    await page.getByLabel('Check-in code', { exact: true }).fill(pass);
    await page.getByRole('button', { name: 'Verify pass', exact: true }).click();
    await page.getByText('entry verified', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Verify pass', exact: true }).click();
    await page.getByText('This pass has already been redeemed', { exact: true }).waitFor();
    await student.getByRole('button', { name: 'Generate pass', exact: true }).click();
    await student.getByText('This check-in pass has already been used', { exact: true }).waitFor();
    await page.getByLabel('Announcement', { exact: true }).fill('Demos start at noon');
    await page.getByRole('button', { name: 'Post announcement' }).click();
    await page.getByText('Announcement posted.').waitFor();
    await page.getByLabel('Judge email').fill('judge@example.test');
    await page.getByRole('button', { name: 'Assign judge' }).click();
    await page.getByText('Judge assigned.').waitFor();
    await student.reload();
    await student.getByText('Demos start at noon').waitFor();
    await student.getByLabel('Subject', { exact: true }).fill('Demo room');
    await student.getByLabel('Question', { exact: true }).fill('Where do we present?');
    await student.getByRole('button', { name: 'Open ticket' }).click();
    await student.getByText('Ticket opened.').waitFor();
    await page.reload();
    await page.getByLabel('Reply', { exact: true }).fill('Room 12');
    await page.getByRole('button', { name: 'Send reply' }).click();
    await page.getByText('Reply sent.').waitFor();
    await page.getByLabel('Ticket status').selectOption('Resolved');
    await page.getByRole('button', { name: 'Update status' }).click();
    await page.getByText('Status updated.').waitFor();
    const judgeContext = await page.context().browser().newContext();
    try {
      const judge = await judgeContext.newPage();
      track(judge);
      await judge.goto('http://localhost:8080/auth/login?role=judge');
      await judge.getByLabel('Email', {exact:true}).fill('judge@example.test');
      await judge.getByLabel('Password', {exact:true}).fill('browser-test-password');
      await judge.getByRole('button', {name:'Login', exact:true}).click();
      const card = judge.getByRole('article').filter({hasText: teamName});
      const download = judge.waitForEvent('download');
      await card.getByRole('button', {name:'Download PDF'}).click();
      if (await (await download).failure()) throw new Error('Judge PDF download failed');
      await card.getByLabel('Score out of 100').fill('87');
      await card.getByLabel('Feedback').fill('Clear demonstration');
      await card.getByRole('button', {name:'Save evaluation'}).click();
      await card.getByText('Evaluation saved.').waitFor();
    } finally { await judgeContext.close(); }
    await student.reload();
    await student.getByText(teamName + ' — 87', {exact:true}).waitFor();
    await student.getByRole('heading', {name:'Demo room · Resolved'}).waitFor();
    await student.getByText('Room 12', {exact:false}).waitFor();
    for (const width of [320, 390, 768, 1440]) {
      await student.setViewportSize({ width, height: 900 });
      const overflow = await student.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
      if (overflow) throw new Error(`Horizontal overflow at ${width}px`);
    }
    await student.evaluate(() => window.scrollTo(0, 0));
    await student.screenshot({ path: 'test-results/event-student-desktop.png', fullPage: true });
    await student.setViewportSize({ width: 390, height: 844 });
    await student.screenshot({ path: 'test-results/event-student-mobile.png', fullPage: true });
    await student.goto('http://localhost:8080/admin');
    await student.waitForURL('http://localhost:8080/');
    await student.goto('http://localhost:8080/events/missing-event');
    await student.getByRole('alert').filter({ hasText: 'Hackathon not found' }).waitFor();
    await student.goto('http://localhost:8080/hackathons');
    await student.getByLabel('Find a hackathon').fill('nonexistent-filter');
    await student.getByText('No matching events. Try another search.', { exact: true }).waitFor();
    await student.getByRole('button', { name: 'Open menu', exact: true }).click();
    await student.getByRole('button', { name: 'Logout', exact: true }).last().click();
    await student.goto('http://localhost:8080/student');
    await student.waitForURL('**/role-select');
    if (errors.length) throw new Error(errors.join('\n'));
    return 'PASS: event creation, separate student signup, team registration, repository + PDF submission, download, reload persistence, organizer visibility, pass rotation, duplicate rejection, role protection, logout, empty/404 states, 320/390/768/1440px layout, and no legacy sync requests.';
  } finally { await studentContext.close(); }
}
